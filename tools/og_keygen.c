/* Generates the OdinGuard server key pair (Monocypher EdDSA, BLAKE2b variant).
 *   og_keygen <keys-dir> <pubkey-header>
 * writes <keys-dir>/server.seed (secret, 64 hex = og_key / ODINGUARD_KEY) and the public key header for the DLL.
 * An existing seed is reused, so the header can be regenerated. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "../third_party/monocypher.h"

static void hex(const unsigned char *p, size_t n, char *out)
{
    size_t i;
    for (i = 0; i < n; i++) sprintf(out + i * 2, "%02x", p[i]);
}

int main(int argc, char **argv)
{
    unsigned char seed[32], sk[64], pk[32];
    char path[1024], seed_hex[65], pk_hex[65];
    FILE *f;
    size_t i;
    if (argc != 3) { fprintf(stderr, "usage: og_keygen <keys-dir> <pubkey-header>\n"); return 1; }
    snprintf(path, sizeof path, "%s/server.seed", argv[1]);
    f = fopen(path, "r");
    if (f) {
        if (fscanf(f, "%64s", seed_hex) != 1 || strlen(seed_hex) != 64) { fprintf(stderr, "bad seed file\n"); return 1; }
        fclose(f);
        for (i = 0; i < 32; i++) { unsigned v; sscanf(seed_hex + i * 2, "%2x", &v); seed[i] = (unsigned char)v; }
    } else {
        f = fopen("/dev/urandom", "rb");
        if (!f || fread(seed, 1, 32, f) != 32) { fprintf(stderr, "no random source\n"); return 1; }
        fclose(f);
        hex(seed, 32, seed_hex);
        f = fopen(path, "w");
        if (!f) { perror(path); return 1; }
        fprintf(f, "%s\n", seed_hex);
        fclose(f);
        fprintf(stderr, "new seed written to %s (keep it secret)\n", path);
    }
    crypto_eddsa_key_pair(sk, pk, seed);
    hex(pk, 32, pk_hex);
    f = fopen(argv[2], "w");
    if (!f) { perror(argv[2]); return 1; }
    fprintf(f, "/* Generated by tools/og_keygen.c: public key of the server (not secret). */\n"
               "#ifndef OG_PUBKEY_H\n#define OG_PUBKEY_H\nstatic const uint8_t og_server_pubkey[32] = {");
    for (i = 0; i < 32; i++) fprintf(f, "%s0x%02x", i ? "," : "", pk[i]);
    fprintf(f, "};\n#define OG_SERVER_PUBKEY_HEX \"%s\"\n#endif\n", pk_hex);
    fclose(f);
    printf("public key %s\n", pk_hex);
    crypto_wipe(sk, sizeof sk);
    crypto_wipe(seed, sizeof seed);
    return 0;
}
